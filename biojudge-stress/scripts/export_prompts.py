"""Write paper/prompts_appendix.tex straight from biojudge/prompts.py and biojudge/perturb.py,
so the appendix always quotes the exact strings the pipeline sent.

    python scripts/export_prompts.py --out paper/prompts_appendix.tex
"""
from __future__ import annotations

import argparse
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from biojudge import perturb as X  # noqa: E402
from biojudge import prompts as P  # noqa: E402

_REPL = [("\\", "\\textbackslash{}"), ("{", "\\{"), ("}", "\\}"), ("_", "\\_"), ("%", "\\%"), ("&", "\\&"),
         ("#", "\\#"), ("$", "\\$"), ("~", "\\textasciitilde{}"), ("^", "\\textasciicircum{}")]


def esc(s: str) -> str:
    """Single-pass LaTeX escaping (so the braces produced for backslashes are not escaped twice)."""
    table = dict(_REPL)
    out = "".join(table.get(ch, ch) for ch in s)
    return out.replace("\n\n", "\\par\\smallskip ").replace("\n", "\\newline ")


def block(title: str, text: str) -> str:
    return (f"\\noindent\\textbf{{{title}}}\\par\\nopagebreak\n"
            f"\\begin{{promptbox}}{esc(text)}\\end{{promptbox}}\n\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="paper/prompts_appendix.tex")
    a = ap.parse_args()
    parts = ["% Auto-generated by scripts/export_prompts.py -- do not edit by hand.\n"]
    parts.append(block("Forced-answer rationale (system)", P.GEN_SYSTEM))
    parts.append(block("Forced-answer rationale (user)", P.GEN_USER))
    parts.append(block("Solo answer (user)", P.SOLO_USER))
    parts.append(block("Padding agent (user)", P.PAD_USER))
    parts.append(block("Normalizer agent (user)", P.NORM_USER))
    parts.append(block("Pairwise verifier (system, base)", P.JUDGE_SYSTEM_BASE))
    parts.append(block("Debiasing clause (appended in debias protocols)", P.DEBIAS_CLAUSE.strip()))
    parts.append(block("Pairwise verifier (user)", P.JUDGE_USER))
    parts.append(block("Best-of-N selector (system, base)", P.SELECT_SYSTEM_BASE))
    parts.append(block("Edit: authority prefix", X.AUTHORITY_PREFIX))
    parts.append(block("Edit: confidence prefix / suffix", X.CONFIDENCE_PREFIX + " ... " + X.CONFIDENCE_SUFFIX))
    parts.append(block("Edit: note to evaluator", X.INJECTION_SUFFIX))
    parts.append(block("Edit: fabricated references (two sampled per response)", "\n".join(X.FAKE_CITATIONS)))
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    with open(a.out, "w") as f:
        f.write("".join(parts))
    print(f"[prompts] wrote {a.out}")


if __name__ == "__main__":
    main()
